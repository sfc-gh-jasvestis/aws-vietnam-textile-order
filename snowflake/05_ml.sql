-- Late-shipment risk scoring and order shipment forecast over the synthetic snapshot.
-- Predicts P(confirmed late shipment in the next 7 days) per factory and
-- reports out-of-time holdout metrics; nothing is seeded as a prediction.
USE DATABASE IDENTIFIER($DEMO_DB);
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE VIEW ML.LATE_FEATURES AS
SELECT r.ENTITY_ID, r.EVENT_DATE, m.CATEGORY, m.RISK_TIER, m.PROGRAM_YEARS,
       r.WIP_GAP_PCT, r.LATE_PCT,
       AVG(r.WIP_GAP_PCT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 6 PRECEDING AND CURRENT ROW) AS WIP_GAP_7D,
       SUM(r.CONFIRMED_COUNT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 29 PRECEDING AND CURRENT ROW) AS CONFIRMED_30D,
       -- Days since the last WIP status review was due, and the 30-day return rate.
       DATEDIFF('day', MAX(IFF(r.REVIEW_DUE = 1, r.EVENT_DATE, NULL)) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW), r.EVENT_DATE) AS DAYS_SINCE_REVIEW,
       COALESCE(SUM(r.REVIEW_DONE) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 29 PRECEDING AND CURRENT ROW)
         / NULLIF(SUM(r.REVIEW_DUE) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 29 PRECEDING AND CURRENT ROW), 0), 1) AS REVIEW_RATE_30D,
       IFF(SUM(r.CONFIRMED_COUNT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) > 0,
           'LATE', 'OK') AS LABEL,
       COUNT(*) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) AS FUTURE_DAYS
FROM RAW.FACTORY_DAILY r JOIN RAW.FACTORIES m ON m.ID = r.ENTITY_ID
-- Grid power curtailments are area-wide, not factory-driven, so they are excluded from training.
WHERE r.RISK_SIGNAL <> 'Grid power curtailment';

-- Time-based split: train on older labelled days, hold out the most recent 14 labelled days.
CREATE VIEW ML.LATE_TRAIN AS
SELECT CATEGORY, RISK_TIER, PROGRAM_YEARS, WIP_GAP_PCT, LATE_PCT, WIP_GAP_7D, CONFIRMED_30D, DAYS_SINCE_REVIEW, REVIEW_RATE_30D, LABEL
FROM ML.LATE_FEATURES
WHERE FUTURE_DAYS = 7 AND EVENT_DATE < DATEADD('day', -21, CURRENT_DATE());

CREATE VIEW ML.LATE_HOLDOUT AS
SELECT ENTITY_ID, EVENT_DATE, CATEGORY, RISK_TIER, PROGRAM_YEARS, WIP_GAP_PCT, LATE_PCT, WIP_GAP_7D, CONFIRMED_30D, DAYS_SINCE_REVIEW, REVIEW_RATE_30D, LABEL
FROM ML.LATE_FEATURES
WHERE FUTURE_DAYS = 7 AND EVENT_DATE >= DATEADD('day', -21, CURRENT_DATE());

CREATE SNOWFLAKE.ML.CLASSIFICATION ML.LATE_RISK_MODEL(
  INPUT_DATA => TABLE(ML.LATE_TRAIN),
  TARGET_COLNAME => 'LABEL'
);

-- Out-of-time holdout: precision/recall at 0.5 versus the base rate.
CREATE TABLE ML.LATE_RISK_HOLDOUT_METRICS AS
WITH scored AS (
  SELECT LABEL, ML.LATE_RISK_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
           'CATEGORY', CATEGORY, 'RISK_TIER', RISK_TIER, 'PROGRAM_YEARS', PROGRAM_YEARS,
           'WIP_GAP_PCT', WIP_GAP_PCT, 'LATE_PCT', LATE_PCT,
           'WIP_GAP_7D', WIP_GAP_7D, 'CONFIRMED_30D', CONFIRMED_30D,
           'DAYS_SINCE_REVIEW', DAYS_SINCE_REVIEW, 'REVIEW_RATE_30D', REVIEW_RATE_30D)):probability:LATE::FLOAT AS P
  FROM ML.LATE_HOLDOUT
)
SELECT COUNT(*) AS N,
       AVG(IFF(LABEL = 'LATE', 1, 0)) AS BASE_RATE,
       SUM(IFF(P >= 0.5 AND LABEL = 'LATE', 1, 0)) / NULLIF(SUM(IFF(P >= 0.5, 1, 0)), 0) AS PRECISION_AT_50,
       SUM(IFF(P >= 0.5 AND LABEL = 'LATE', 1, 0)) / NULLIF(SUM(IFF(LABEL = 'LATE', 1, 0)), 0) AS RECALL_AT_50,
       CURRENT_TIMESTAMP() AS EVALUATED_AT
FROM scored;

-- Latest-day score per factory (label unknown, so excluded from features).
CREATE TABLE ML.LATE_RISK_SCORES AS
WITH latest AS (
  SELECT * FROM ML.LATE_FEATURES
  QUALIFY ROW_NUMBER() OVER (PARTITION BY ENTITY_ID ORDER BY EVENT_DATE DESC) = 1
), scored AS (
  SELECT ENTITY_ID, EVENT_DATE,
         ML.LATE_RISK_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
           'CATEGORY', CATEGORY, 'RISK_TIER', RISK_TIER, 'PROGRAM_YEARS', PROGRAM_YEARS,
           'WIP_GAP_PCT', WIP_GAP_PCT, 'LATE_PCT', LATE_PCT,
           'WIP_GAP_7D', WIP_GAP_7D, 'CONFIRMED_30D', CONFIRMED_30D,
           'DAYS_SINCE_REVIEW', DAYS_SINCE_REVIEW, 'REVIEW_RATE_30D', REVIEW_RATE_30D)) AS P
  FROM latest
)
SELECT ENTITY_ID, EVENT_DATE AS SCORED_AS_OF,
       ROUND(P:probability:LATE::FLOAT, 4) AS LATE_PROB_7D,
       CASE WHEN P:probability:LATE::FLOAT >= 0.5 THEN 'High'
            WHEN P:probability:LATE::FLOAT >= 0.25 THEN 'Medium' ELSE 'Low' END AS RISK_BAND,
       CURRENT_TIMESTAMP() AS SCORED_AT
FROM scored;

-- Network-wide daily order shipment forecast (14 days), for container booking and port cut-off planning.
CREATE VIEW ML.DAILY_SHIPMENTS AS
SELECT EVENT_DATE::TIMESTAMP_NTZ AS TS, SUM(SHIPMENT_COUNT)::FLOAT AS SHIPMENT_COUNT
FROM RAW.FACTORY_DAILY GROUP BY EVENT_DATE;

CREATE SNOWFLAKE.ML.FORECAST ML.SHIPMENT_FORECAST_MODEL(
  INPUT_DATA => TABLE(ML.DAILY_SHIPMENTS),
  TIMESTAMP_COLNAME => 'TS',
  TARGET_COLNAME => 'SHIPMENT_COUNT'
);

CREATE TABLE ML.SHIPMENT_FORECAST AS
SELECT TS::DATE AS FORECAST_DATE, GREATEST(0, FORECAST) AS SHIPMENT_COUNT,
       GREATEST(0, LOWER_BOUND) AS LOWER_BOUND, UPPER_BOUND
FROM TABLE(ML.SHIPMENT_FORECAST_MODEL!FORECAST(FORECASTING_PERIODS => 14));
