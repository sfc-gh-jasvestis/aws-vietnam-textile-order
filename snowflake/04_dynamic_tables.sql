-- On-demand snapshots. No automatic freshness claim.
USE DATABASE IDENTIFIER($DEMO_DB);
USE SCHEMA CURATED;
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT factory.ID AS ENTITY_ID, factory.NAME AS ENTITY_NAME,
       factory.REGION, factory.CATEGORY, factory.RISK_TIER, factory.STATUS,
       COUNT(*) AS EVENT_COUNT,
       SUM(observation.SHIPMENT_COUNT) AS SHIPMENT_COUNT,
       SUM(observation.ONTIME_KUNITS) AS ONTIME_KUNITS,
       SUM(observation.SHIPPED_KUNITS) AS SHIPPED_KUNITS,
       SUM(observation.FLAG_COUNT) AS FLAG_COUNT,
       SUM(observation.CONFIRMED_COUNT) AS CONFIRMED_COUNT,
       SUM(observation.LOTS_QUARANTINED) AS QUARANTINED_COUNT,
       SUM(observation.REVIEW_DUE) AS REVIEW_DUE,
       SUM(observation.REVIEW_DONE) AS REVIEW_DONE,
       100.0 * SUM(observation.ONTIME_KUNITS) / NULLIF(SUM(observation.SHIPPED_KUNITS), 0) AS ON_TIME_PCT,
       100.0 * SUM(observation.CONFIRMED_COUNT) / NULLIF(SUM(observation.FLAG_COUNT), 0) AS FLAG_PRECISION_PCT,
       100.0 * SUM(observation.REVIEW_DONE) / NULLIF(SUM(observation.REVIEW_DUE), 0) AS REVIEW_PCT,
       AVG(observation.WIP_GAP_PCT) AS AVG_WIP_GAP_PCT,
       MAX(observation.EVENT_DATE) AS SOURCE_WATERMARK
FROM RAW.FACTORY_DAILY observation
JOIN RAW.FACTORIES factory ON factory.ID = observation.ENTITY_ID
GROUP BY factory.ID, factory.NAME, factory.REGION, factory.CATEGORY, factory.RISK_TIER, factory.STATUS;

CREATE DYNAMIC TABLE CURATED.TREND_ANALYSIS
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT EVENT_DATE AS METRIC_DATE, COUNT(*) AS EVENT_COUNT,
       SUM(SHIPMENT_COUNT) AS SHIPMENT_COUNT, SUM(ONTIME_KUNITS) AS ONTIME_KUNITS,
       SUM(SHIPPED_KUNITS) AS SHIPPED_KUNITS,
       SUM(FLAG_COUNT) AS FLAG_COUNT, SUM(CONFIRMED_COUNT) AS CONFIRMED_COUNT,
       100.0 * SUM(ONTIME_KUNITS) / NULLIF(SUM(SHIPPED_KUNITS), 0) AS ON_TIME_PCT
FROM RAW.FACTORY_DAILY
GROUP BY EVENT_DATE;

CREATE DYNAMIC TABLE CURATED.SIGNAL_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT RISK_SIGNAL, SUM(FLAG_COUNT) AS FLAG_COUNT,
       SUM(CONFIRMED_COUNT) AS CONFIRMED_COUNT,
       SUM(LOTS_QUARANTINED) AS QUARANTINED_COUNT,
       SUM(ONTIME_KUNITS) AS FLAGGED_DAY_ONTIME_KUNITS,
       100.0 * SUM(CONFIRMED_COUNT) / NULLIF(SUM(FLAG_COUNT), 0) AS FLAG_PRECISION_PCT
FROM RAW.FACTORY_DAILY
WHERE FLAG_COUNT > 0
GROUP BY RISK_SIGNAL;

CREATE DYNAMIC TABLE CURATED.KPI_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
WITH observations AS (
  SELECT SUM(SHIPMENT_COUNT) AS SHIPMENTS, SUM(ONTIME_KUNITS) AS ONTIME,
         SUM(SHIPPED_KUNITS) AS SHIPPED,
         SUM(FLAG_COUNT) AS FLAGS, SUM(CONFIRMED_COUNT) AS CONFIRMED,
         SUM(LOTS_QUARANTINED) AS QUARANTINED,
         SUM(REVIEW_DUE) AS REVIEW_DUE, SUM(REVIEW_DONE) AS REVIEW_DONE,
         MAX(EVENT_DATE) AS SOURCE_WATERMARK
  FROM RAW.FACTORY_DAILY
), portfolio AS (SELECT COUNT(*) AS FACTORY_COUNT FROM RAW.FACTORIES),
documents AS (
  SELECT 100.0 * SUM(LEAST(ON_FILE_QTY, REQUIRED_QTY)) / NULLIF(SUM(REQUIRED_QTY), 0) AS COVERAGE_PCT,
         SUM(PENDING_QTY) AS PENDING, SUM(REQUIRED_QTY) AS REGISTERED
  FROM RAW.STYLE_APPROVALS
), metrics AS (
  SELECT 1 AS SORT_ORDER, 'On-Time Shipment (pieces)' AS TITLE,
         100.0 * ONTIME / NULLIF(SHIPPED, 0) AS VALUE_NUM, '%' AS UNIT FROM observations
  UNION ALL SELECT 2, 'Order Shipments', SHIPMENTS, '' FROM observations
  UNION ALL SELECT 3, 'Pieces Shipped (millions)', SHIPPED / 1e3, '' FROM observations
  UNION ALL SELECT 4, 'Order Risk Flags', FLAGS, '' FROM observations
  UNION ALL SELECT 5, 'Confirmed Late Shipments', CONFIRMED, '' FROM observations
  UNION ALL SELECT 6, 'Flag Precision', 100.0 * CONFIRMED / NULLIF(FLAGS, 0), '%' FROM observations
  UNION ALL SELECT 7, 'Lots Held at Final Inspection', QUARANTINED, '' FROM observations
  UNION ALL SELECT 8, 'WIP Review Completion', 100.0 * REVIEW_DONE / NULLIF(REVIEW_DUE, 0), '%' FROM observations
  UNION ALL SELECT 9, 'Factories Monitored', FACTORY_COUNT, '' FROM portfolio
  UNION ALL SELECT 10, 'PP Sample Approval Coverage', COVERAGE_PCT, '%' FROM documents
  UNION ALL SELECT 11, 'Approvals Pending', PENDING, '' FROM documents
  UNION ALL SELECT 12, 'Active Styles', REGISTERED, '' FROM documents
)
SELECT metrics.SORT_ORDER, metrics.TITLE, metrics.VALUE_NUM,
       IFF(metrics.VALUE_NUM IS NULL, 'Unavailable',
           CASE WHEN metrics.UNIT = '' THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM), '999,999,999,990'))
                ELSE TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 1), '990.0')) END || metrics.UNIT) AS DISPLAY,
       'neutral' AS STATUS, observations.SOURCE_WATERMARK
FROM metrics CROSS JOIN observations;

ALTER DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.TREND_ANALYSIS SUSPEND;
ALTER DYNAMIC TABLE CURATED.SIGNAL_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.KPI_SUMMARY SUSPEND;
